/**
 * 모자이크·검출·추적 기본값. glm.md 9장에 따라 최종 수치는 아직 확정되지 않았다(초안).
 * 값을 바꿀 때는 이 파일만 고치면 된다.
 */

export type Sensitivity = 'low' | 'normal' | 'high'
export type OutputQuality = 'medium' | 'high' | 'very-high'

export interface SensitivityPreset {
  label: string
  /** 새 얼굴로 인정하는 검출 신뢰도 기준값. 낮을수록 더 많이 잡는다. */
  scoreThreshold: number
  /**
   * 전체 화면 검출에 더해 화면을 나눠 확대 검출할 때, 화면의 짧은 변을 몇 장으로 나눌지(비어 있으면 타일 없음).
   * 긴 변의 장수는 타일이 정사각형에 가깝게 되도록 화면 비율에 맞춰 정한다(core/geometry.ts 의 tileGrid).
   * 검출 모델의 입력이 정사각형이라, 타일이 길쭉하면 입력의 절반이 빈 여백으로 버려져 얼굴이 작게 들어간다.
   *
   * 여러 개를 적으면 타일 검출 때마다 차례로 돌아가며 쓴다. 타일 경계에 걸린 얼굴은 양쪽 타일 모두에서 잘려
   * 잡히지 않는데, 격자가 다르면 경계의 위치도 달라서 한쪽 격자에서는 온전히 들어간다(공개 시험 영상에서 확인).
   */
  tileGrids: number[]
  /** 전체 화면 검출을 몇 프레임마다 할지(30fps 기준). 사이 프레임은 추적 보간으로 채운다. */
  fullIntervalFrames: number
  /**
   * 타일 검출을 몇 프레임마다 할지(30fps 기준). 전체 화면 검출을 하는 프레임에 함께 한다.
   * 프레임 속도가 다른 영상은 같은 시간 간격이 되도록 맞춘다(60fps 면 두 배).
   * 사이 프레임은 추적 보간으로 채운다. 추론 1회가 수십 ms 라 매 프레임 타일 검출은 너무 느리다(2단계 측정).
   */
  tileIntervalFrames: number
}

/**
 * 값의 근거: 실제 교실 영상(1080p 30fps, 28초, 학생 얼굴 폭 50~120px) 측정, 2026-11-22.
 *
 * 1) 타일 장수: 확실한 얼굴이 프레임마다 잡히는 비율이 2x2 타일 33% → 4x2 타일 62% → 5x3 타일 79% 였다.
 *    고개를 숙이거나 돌린 얼굴은 크게 확대해 넣을수록 잘 잡힌다. 예전 기본값(2x2)은 확대가 모자랐다.
 * 2) 검출 간격: 약한 검출로 얼굴을 이어 가고 끊긴 사이를 계속 가리게 된 뒤로는(core/tracker.ts),
 *    검출을 드물게 해도 가림이 거의 줄지 않았다. 같은 처리 시간이면 "크게 확대해서 드물게" 보는 쪽이
 *    "조금 확대해서 자주" 보는 쪽보다 많이 가렸다(5x3 을 8프레임마다 > 4x2 를 4프레임마다).
 * 3) 격자 번갈아 쓰기: 5x3 한 가지만 쓰면 타일 경계에 걸린 얼굴을 영상 내내 놓치는 일이 있었다(공개 시험 영상의 옆얼굴).
 *    5x3 과 4x2 를 번갈아 쓰면 경계 위치가 달라 서로 메운다.
 *
 * 4) 처리 시간: '보통'은 프레임당 추론 횟수를 예전과 같은 수준으로 맞췄다. 사양 점검(검출 속도·예상 처리 시간)의
 *    기준값이 예전 '보통'의 처리량에 맞춰져 있어서, 더 무겁게 하면 같은 컴퓨터가 한 단계 낮게 판정되기 때문이다.
 *    더 많이 가리고 싶으면 '꼼꼼하게'를 쓴다(타일을 4프레임마다 하면 88% / 66%, 2프레임마다 + 기준값 0.3 이면 아래 수치).
 *
 * 정밀 검출이 확인한 얼굴이 가려진 비율(0.8점 이상 / 0.6~0.8점 / 0.4~0.6점)과 프레임당 평균 추론 횟수:
 *   예전: 빠르게 16% / 35% /  7% (1.0회)   보통 47% / 59% / 22% (2.3회)   꼼꼼하게 99.9% / 76% / 37% (5.5회)
 *   지금: 빠르게 94% / 79% / 51% (1.5회)   보통 99.4% / 83% / 60% (2.4회)  꼼꼼하게 100% / 95% / 83% (6.3회)
 * 모자이크가 덮는 넓이(화면 전체 대비 평균): 빠르게 4.9%, 보통 6.6%, 꼼꼼하게 14.2%.
 * 점수가 낮은 쪽일수록 고개를 숙이거나 돌린 얼굴이 많다(얼굴이 아닌 것도 일부 섞여 있다).
 * 내 영상에서 다시 재려면: npm run e2e:miss -- --video=경로
 */
export const SENSITIVITY_PRESETS: Record<Sensitivity, SensitivityPreset> = {
  low: { label: '빠르게 (드문드문 확인, 어려운 얼굴은 놓칠 수 있음)', scoreThreshold: 0.4, tileGrids: [3, 2], fullIntervalFrames: 2, tileIntervalFrames: 12 },
  normal: { label: '보통', scoreThreshold: 0.4, tileGrids: [3, 2], fullIntervalFrames: 2, tileIntervalFrames: 6 },
  high: { label: '꼼꼼하게 (고개 숙인 얼굴·아주 작은 얼굴까지, 느림)', scoreThreshold: 0.3, tileGrids: [3, 2], fullIntervalFrames: 2, tileIntervalFrames: 2 },
}

